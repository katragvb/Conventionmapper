using System;
using System.Collections.Generic;
using System.Linq;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace ConventionMapper.SourceGenerator
{
    /// <summary>
    /// What the generator knows about EF Core entities: entity types (DbSet&lt;T&gt;, IEntityTypeConfiguration&lt;T&gt;,
    /// modelBuilder.Entity&lt;T&gt;() and the types their navigations reach), and, from the fluent configuration in
    /// OnModelCreating / Configure in this compilation, keys, foreign keys, maximum lengths and generated values.
    /// Scaffolded entities carry no attributes, so the fluent configuration is where that information lives.
    /// </summary>
    internal sealed class EfModel
    {
        private readonly Compilation _compilation;
        private readonly CancellationToken _ct;
        private readonly HashSet<ITypeSymbol> _entities = new HashSet<ITypeSymbol>(SymbolEqualityComparer.Default);
        private readonly Dictionary<ITypeSymbol, HashSet<string>> _keys = new Dictionary<ITypeSymbol, HashSet<string>>(SymbolEqualityComparer.Default);
        private readonly Dictionary<ITypeSymbol, HashSet<string>> _foreignKeys = new Dictionary<ITypeSymbol, HashSet<string>>(SymbolEqualityComparer.Default);
        private readonly Dictionary<ITypeSymbol, Dictionary<string, int>> _maxLengths = new Dictionary<ITypeSymbol, Dictionary<string, int>>(SymbolEqualityComparer.Default);
        private readonly Dictionary<ITypeSymbol, Dictionary<string, bool>> _generated = new Dictionary<ITypeSymbol, Dictionary<string, bool>>(SymbolEqualityComparer.Default);

        /// <summary>Columns with HasDefaultValueSql: the database fills them only when an insert leaves them out.</summary>
        private readonly Dictionary<ITypeSymbol, Dictionary<string, bool>> _defaultSql = new Dictionary<ITypeSymbol, Dictionary<string, bool>>(SymbolEqualityComparer.Default);

        private EfModel(Compilation compilation, CancellationToken ct)
        {
            _compilation = compilation;
            _ct = ct;
        }

        public static EfModel Build(Compilation compilation, CancellationToken ct)
        {
            var model = new EfModel(compilation, ct);
            if (compilation.GetTypeByMetadataName("Microsoft.EntityFrameworkCore.DbContext") != null)
            {
                var roots = new List<ITypeSymbol>();
                model.FindDeclaredEntities(roots);
                model.ReadFluentConfiguration(roots);
                model.AddReachable(roots);
            }
            return model;
        }

        public bool IsEntity(ITypeSymbol type) => _entities.Contains(type.OriginalDefinition);

        /// <summary>Primary key members from HasKey (null when the configuration doesn't say).</summary>
        public IReadOnlyCollection<string>? Keys(ITypeSymbol type) => _keys.TryGetValue(type.OriginalDefinition, out var keys) ? keys : null;

        public bool IsForeignKey(ITypeSymbol type, string member) =>
            _foreignKeys.TryGetValue(type.OriginalDefinition, out var keys) && keys.Contains(member);

        public int? MaxLength(ITypeSymbol type, string member) =>
            _maxLengths.TryGetValue(type.OriginalDefinition, out var lengths) && lengths.TryGetValue(member, out var length) ? length : (int?)null;

        /// <summary>
        /// True: generated by the database (identity, computed, ValueGeneratedOn*); false: ValueGeneratedNever; null: not configured.
        /// A default (HasDefaultValueSql) is not generation: the database uses it only when the insert leaves the column out, so
        /// copying a value into the column is normal. See <see cref="HasDefaultSql"/>.
        /// </summary>
        public bool? IsGenerated(ITypeSymbol type, string member) =>
            _generated.TryGetValue(type.OriginalDefinition, out var values) && values.TryGetValue(member, out var generated) ? generated : (bool?)null;

        /// <summary>The column has a database default (HasDefaultValueSql), such as newid() or NEXT VALUE FOR a sequence on a key.</summary>
        public bool HasDefaultSql(ITypeSymbol type, string member) =>
            _defaultSql.TryGetValue(type.OriginalDefinition, out var values) && values.ContainsKey(member);

        // ------------------------------------------------------------------ entity types

        private void FindDeclaredEntities(List<ITypeSymbol> roots)
        {
            var dbContext = _compilation.GetTypeByMetadataName("Microsoft.EntityFrameworkCore.DbContext");
            var dbSet = _compilation.GetTypeByMetadataName("Microsoft.EntityFrameworkCore.DbSet`1");
            var configuration = _compilation.GetTypeByMetadataName("Microsoft.EntityFrameworkCore.IEntityTypeConfiguration`1");

            var assemblies = new List<IAssemblySymbol> { _compilation.Assembly };
            foreach (var reference in _compilation.SourceModule.ReferencedAssemblySymbols)
                if (reference.Modules.Any(m => m.ReferencedAssemblySymbols.Any(r => r.Name == "Microsoft.EntityFrameworkCore")))
                    assemblies.Add(reference);

            foreach (var assembly in assemblies)
            {
                foreach (var type in AllTypes(assembly.GlobalNamespace))
                {
                    _ct.ThrowIfCancellationRequested();
                    for (var t = type.BaseType; t != null; t = t.BaseType)
                    {
                        if (!SymbolEqualityComparer.Default.Equals(t, dbContext)) continue;
                        foreach (var property in type.GetMembers().OfType<IPropertySymbol>())
                            if (property.Type is INamedTypeSymbol set && SymbolEqualityComparer.Default.Equals(set.OriginalDefinition, dbSet))
                                roots.Add(set.TypeArguments[0]);
                        break;
                    }
                    if (configuration != null)
                        foreach (var i in type.AllInterfaces)
                            if (SymbolEqualityComparer.Default.Equals(i.OriginalDefinition, configuration)) roots.Add(i.TypeArguments[0]);
                }
            }
        }

        /// <summary>Navigations make the types they reach entities too (EF discovers them the same way).</summary>
        private void AddReachable(List<ITypeSymbol> roots)
        {
            var pending = new Queue<ITypeSymbol>(roots);
            while (pending.Count > 0)
            {
                var entity = pending.Dequeue();
                if (!(entity is INamedTypeSymbol named) || named.TypeKind != TypeKind.Class || !_entities.Add(named.OriginalDefinition)) continue;
                for (var t = (ITypeSymbol?)named; t != null && t.SpecialType != SpecialType.System_Object; t = t.BaseType)
                    foreach (var property in t.GetMembers().OfType<IPropertySymbol>())
                    {
                        var target = ElementType(property.Type) ?? property.Type;
                        if (IsEntityCandidate(target)) pending.Enqueue(target);
                    }
            }
        }

        /// <summary>A class that could be an entity: not a framework type, string or collection.</summary>
        public static bool IsEntityCandidate(ITypeSymbol type) =>
            type is INamedTypeSymbol named && named.TypeKind == TypeKind.Class && named.SpecialType == SpecialType.None &&
            !(named.ContainingNamespace?.ToDisplayString() ?? string.Empty).StartsWith("System", StringComparison.Ordinal) &&
            ElementType(named) == null;

        public static ITypeSymbol? ElementType(ITypeSymbol type)
        {
            if (type.SpecialType == SpecialType.System_String) return null;
            if (type is IArrayTypeSymbol array) return array.ElementType;
            if (type is INamedTypeSymbol named && named.OriginalDefinition.SpecialType == SpecialType.System_Collections_Generic_IEnumerable_T)
                return named.TypeArguments[0];
            foreach (var i in type.AllInterfaces)
                if (i.OriginalDefinition.SpecialType == SpecialType.System_Collections_Generic_IEnumerable_T) return i.TypeArguments[0];
            return null;
        }

        private static IEnumerable<INamedTypeSymbol> AllTypes(INamespaceSymbol ns)
        {
            foreach (var type in ns.GetTypeMembers())
            {
                yield return type;
                foreach (var nested in Nested(type)) yield return nested;
            }
            foreach (var child in ns.GetNamespaceMembers())
                foreach (var type in AllTypes(child))
                    yield return type;
        }

        private static IEnumerable<INamedTypeSymbol> Nested(INamedTypeSymbol type)
        {
            foreach (var nested in type.GetTypeMembers())
            {
                yield return nested;
                foreach (var deeper in Nested(nested)) yield return deeper;
            }
        }

        // ------------------------------------------------------------------ fluent configuration

        private void ReadFluentConfiguration(List<ITypeSymbol> roots)
        {
            foreach (var tree in _compilation.SyntaxTrees)
            {
                _ct.ThrowIfCancellationRequested();
                var text = tree.GetText(_ct).ToString();
                if (text.IndexOf("OnModelCreating", StringComparison.Ordinal) < 0 && text.IndexOf("IEntityTypeConfiguration", StringComparison.Ordinal) < 0) continue;
                var model = _compilation.GetSemanticModel(tree);
                foreach (var invocation in tree.GetRoot(_ct).DescendantNodes().OfType<InvocationExpressionSyntax>())
                {
                    if (!(invocation.Expression is MemberAccessExpressionSyntax access)) continue;
                    var name = access.Name.Identifier.ValueText;
                    switch (name)
                    {
                        case "Entity":
                            if (access.Name is GenericNameSyntax generic && generic.TypeArgumentList.Arguments.Count == 1 &&
                                model.GetTypeInfo(generic.TypeArgumentList.Arguments[0], _ct).Type is ITypeSymbol entityType)
                                roots.Add(entityType);
                            break;
                        case "HasKey":
                        case "HasForeignKey":
                        case "Property":
                            ReadMemberSelection(invocation, name, model);
                            break;
                    }
                }
            }
        }

        /// <summary>HasKey(e => e.Id), HasKey(e => new { e.A, e.B }), HasForeignKey(d => d.CustomerId), Property(e => e.Name).HasMaxLength(50)...</summary>
        private void ReadMemberSelection(InvocationExpressionSyntax invocation, string name, SemanticModel model)
        {
            if (invocation.ArgumentList.Arguments.Count != 1 || !(invocation.ArgumentList.Arguments[0].Expression is LambdaExpressionSyntax lambda)) return;
            var parameter = lambda switch
            {
                SimpleLambdaExpressionSyntax simple => simple.Parameter,
                ParenthesizedLambdaExpressionSyntax parenthesized when parenthesized.ParameterList.Parameters.Count == 1 => parenthesized.ParameterList.Parameters[0],
                _ => null,
            };
            if (parameter == null || !(model.GetDeclaredSymbol(parameter, _ct) is IParameterSymbol symbol)) return;
            var entity = symbol.Type.OriginalDefinition;
            var members = SelectedMembers(lambda.Body).ToList();
            if (members.Count == 0) return;

            switch (name)
            {
                case "HasKey":
                    Set(_keys, entity).UnionWith(members);
                    break;
                case "HasForeignKey":
                    Set(_foreignKeys, entity).UnionWith(members);
                    break;
                case "Property":
                    if (members.Count != 1) return;
                    // Walk the fluent chain: Property(...).HasMaxLength(50).ValueGeneratedOnAdd()...
                    for (SyntaxNode? node = invocation; node?.Parent is MemberAccessExpressionSyntax next && next.Parent is InvocationExpressionSyntax call; node = call)
                    {
                        var step = next.Name.Identifier.ValueText;
                        switch (step)
                        {
                            case "HasMaxLength":
                                if (call.ArgumentList.Arguments.Count == 1 && model.GetConstantValue(call.ArgumentList.Arguments[0].Expression, _ct).Value is int length)
                                    Map(_maxLengths, entity)[members[0]] = length;
                                break;
                            case "ValueGeneratedOnAdd":
                            case "ValueGeneratedOnAddOrUpdate":
                            case "ValueGeneratedOnUpdate":
                            case "UseIdentityColumn":
                            case "UseSqlServerIdentityColumn":
                            case "UseIdentityAlwaysColumn":
                            case "UseIdentityByDefaultColumn":
                            case "HasComputedColumnSql":
                                Map(_generated, entity)[members[0]] = true;
                                break;
                            case "HasDefaultValueSql":
                                Map(_defaultSql, entity)[members[0]] = true;
                                break;
                            case "ValueGeneratedNever":
                                Map(_generated, entity)[members[0]] = false;
                                break;
                        }
                    }
                    break;
            }
        }

        private static IEnumerable<string> SelectedMembers(CSharpSyntaxNode body)
        {
            switch (body)
            {
                case MemberAccessExpressionSyntax member:
                    yield return member.Name.Identifier.ValueText;
                    break;
                case AnonymousObjectCreationExpressionSyntax anonymous:
                    foreach (var initializer in anonymous.Initializers)
                        if (initializer.Expression is MemberAccessExpressionSyntax part) yield return part.Name.Identifier.ValueText;
                    break;
            }
        }

        private static HashSet<string> Set(Dictionary<ITypeSymbol, HashSet<string>> map, ITypeSymbol type)
        {
            if (!map.TryGetValue(type, out var set))
            {
                set = new HashSet<string>(StringComparer.Ordinal);
                map[type] = set;
            }
            return set;
        }

        private static Dictionary<string, T> Map<T>(Dictionary<ITypeSymbol, Dictionary<string, T>> map, ITypeSymbol type)
        {
            if (!map.TryGetValue(type, out var values))
            {
                values = new Dictionary<string, T>(StringComparer.Ordinal);
                map[type] = values;
            }
            return values;
        }
    }
}
