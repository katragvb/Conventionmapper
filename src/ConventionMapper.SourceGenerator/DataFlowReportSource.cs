using System.Collections.Generic;
using System.Text;
using Microsoft.CodeAnalysis.CSharp;

namespace ConventionMapper.SourceGenerator
{
    /// <summary>
    /// Writes ConventionMapper.Generated.DataFlowReport: the assembly's data-flow report as one Markdown document and per
    /// mapper class, plus snapshot helpers for tests (written into the user's assembly, so no test framework is needed).
    /// </summary>
    internal static class DataFlowReportSource
    {
        public const string Title = "# Data-flow report";

        public const string Intro = "Generated at build time by ConventionMapper.SourceGenerator: where every destination member of the generated mappers gets its value, and where members marked `[Sensitive]` can flow.";

        public static string Build(IReadOnlyList<ReportSection> sections, bool includeSnapshotHelpers)
        {
            var markdown = new StringBuilder();
            markdown.AppendLine(Title).AppendLine();
            markdown.AppendLine(Intro).AppendLine();
            foreach (var section in sections) markdown.Append(section.Markdown);

            var sb = new StringBuilder();
            sb.Append("// <auto-generated/>\n");
            sb.Append("#nullable enable\n");
            sb.Append("#pragma warning disable\n");
            sb.Append("namespace ConventionMapper.Generated\n");
            sb.Append("{\n");
            sb.Append("    /// <summary>\n");
            sb.Append("    /// Data-flow report for the [GeneratedMapper] classes in this assembly, as Markdown: the whole assembly in <see cref=\"Markdown\"/>,\n");
            sb.Append("    /// each mapper class in <see cref=\"ByMapper\"/>.");
            if (includeSnapshotHelpers) sb.Append(" Snapshot-test it with <see cref=\"AssertMatches\"/> or <see cref=\"AssertMatchesDirectory\"/>.");
            sb.Append("\n    /// </summary>\n");
            sb.Append("    internal static partial class DataFlowReport\n");
            sb.Append("    {\n");
            sb.Append("        public const string Markdown = ").Append(Verbatim(markdown.ToString())).Append(";\n\n");
            sb.Append("        /// <summary>The report of each [GeneratedMapper] class on its own, by fully qualified class name.</summary>\n");
            sb.Append("        public static readonly global::System.Collections.Generic.IReadOnlyDictionary<string, string> ByMapper =\n");
            sb.Append("            new global::System.Collections.Generic.Dictionary<string, string>(global::System.StringComparer.Ordinal)\n");
            sb.Append("            {\n");
            foreach (var section in sections)
            {
                var single = Title + "\n\n" + section.Markdown;
                sb.Append("                [").Append(SymbolDisplay.FormatLiteral(section.Mapper, true)).Append("] = ").Append(Verbatim(single)).Append(",\n");
            }
            sb.Append("            };\n");
            if (includeSnapshotHelpers) sb.Append(SnapshotHelpers);
            sb.Append("    }\n");
            sb.Append("}\n");
            return sb.ToString();
        }

        private static string Verbatim(string text) => "@\"" + text.Replace("\r\n", "\n").Replace("\"", "\"\"") + "\"";

        // Plain C# 7.3 / netstandard2.0 APIs only: this is compiled into the user's assembly.
        private const string SnapshotHelpers = @"
        /// <summary>Set this environment variable to 1 to rewrite the snapshot files instead of failing.</summary>
        public const string UpdateVariable = ""CONVENTIONMAPPER_UPDATE_SNAPSHOTS"";

        /// <summary>
        /// Compares the whole report with a Markdown file (relative paths start at the folder of the calling source file).
        /// A missing file is created and the call fails so it gets reviewed; with CONVENTIONMAPPER_UPDATE_SNAPSHOTS=1 the
        /// file is rewritten. Line endings and trailing spaces are ignored.
        /// </summary>
        /// <exception cref=""SnapshotMismatchException"">The file differs from the report; the message has a line diff.</exception>
        public static void AssertMatches(string path, [global::System.Runtime.CompilerServices.CallerFilePath] string callerFilePath = """")
        {
            var failures = new global::System.Collections.Generic.List<string>();
            Check(Resolve(path, callerFilePath), Markdown, failures);
            if (failures.Count > 0) throw new SnapshotMismatchException(string.Join(""\n\n"", failures));
        }

        /// <summary>
        /// Compares each mapper class's report with its own file in a folder (""Namespace.MapperName.md""), so changes to
        /// different mappers touch different files. Files for mappers that no longer exist fail the check (and are deleted
        /// with CONVENTIONMAPPER_UPDATE_SNAPSHOTS=1).
        /// </summary>
        /// <exception cref=""SnapshotMismatchException"">A file differs, is missing or is stale; the message lists each one.</exception>
        public static void AssertMatchesDirectory(string directory, [global::System.Runtime.CompilerServices.CallerFilePath] string callerFilePath = """")
        {
            var folder = Resolve(directory, callerFilePath);
            var failures = new global::System.Collections.Generic.List<string>();
            var expected = new global::System.Collections.Generic.HashSet<string>(global::System.StringComparer.OrdinalIgnoreCase);
            foreach (var pair in ByMapper)
            {
                var name = FileName(pair.Key);
                expected.Add(name);
                Check(global::System.IO.Path.Combine(folder, name), pair.Value, failures);
            }
            if (global::System.IO.Directory.Exists(folder))
            {
                foreach (var file in global::System.IO.Directory.GetFiles(folder, ""*.md""))
                {
                    if (expected.Contains(global::System.IO.Path.GetFileName(file))) continue;
                    if (Updating) global::System.IO.File.Delete(file);
                    else failures.Add(""Stale data-flow report: "" + file + "" belongs to no mapper class. Delete it, or run the tests with "" + UpdateVariable + ""=1."");
                }
            }
            if (failures.Count > 0) throw new SnapshotMismatchException(string.Join(""\n\n"", failures));
        }

        /// <summary>Thrown when a data-flow report snapshot does not match the build.</summary>
        public sealed class SnapshotMismatchException : global::System.Exception
        {
            public SnapshotMismatchException(string message) : base(message) { }
        }

        private static bool Updating
        {
            get
            {
                var value = global::System.Environment.GetEnvironmentVariable(UpdateVariable);
                return value == ""1"" || string.Equals(value, ""true"", global::System.StringComparison.OrdinalIgnoreCase);
            }
        }

        private static string FileName(string mapper)
        {
            var chars = mapper.ToCharArray();
            for (var i = 0; i < chars.Length; i++)
                if (!char.IsLetterOrDigit(chars[i]) && chars[i] != '.' && chars[i] != '_' && chars[i] != '-') chars[i] = '_';
            return new string(chars) + "".md"";
        }

        private static void Check(string file, string report, global::System.Collections.Generic.List<string> failures)
        {
            var expected = Normalize(report);
            var exists = global::System.IO.File.Exists(file);
            var actual = exists ? Normalize(global::System.IO.File.ReadAllText(file)) : null;
            if (actual == expected) return;
            if (Updating || !exists)
            {
                var folder = global::System.IO.Path.GetDirectoryName(file);
                if (!string.IsNullOrEmpty(folder)) global::System.IO.Directory.CreateDirectory(folder);
                global::System.IO.File.WriteAllText(file, expected);
            }
            if (Updating) return;
            failures.Add(!exists
                ? ""Created data-flow report "" + file + "": review it and commit it.""
                : ""Data-flow report changed: "" + file + ""\n"" + Diff(actual!, expected) +
                  ""\nIf the change is intended, update the file (run the tests with "" + UpdateVariable + ""=1) and commit it."");
        }

        private static string Normalize(string text)
        {
            var lines = text.Replace(""\r\n"", ""\n"").Replace('\r', '\n').Split('\n');
            var sb = new global::System.Text.StringBuilder(text.Length);
            foreach (var line in lines) sb.Append(line.TrimEnd()).Append('\n');
            return sb.ToString().TrimEnd('\n') + ""\n"";
        }

        /// <summary>Line diff of the committed file (-) against the build (+), with common lines around changes.</summary>
        private static string Diff(string oldText, string newText)
        {
            var a = oldText.Split('\n');
            var b = newText.Split('\n');
            int start = 0, endA = a.Length, endB = b.Length;
            while (start < endA && start < endB && a[start] == b[start]) start++;
            while (endA > start && endB > start && a[endA - 1] == b[endB - 1]) { endA--; endB--; }
            var n = endA - start;
            var m = endB - start;
            var sb = new global::System.Text.StringBuilder();
            if (start > 0) sb.Append(""  "").Append(a[start - 1]).Append('\n');
            if ((long)n * m > 4000000L)
            {
                for (var i = start; i < endA && i < start + 40; i++) sb.Append(""- "").Append(a[i]).Append('\n');
                for (var i = start; i < endB && i < start + 40; i++) sb.Append(""+ "").Append(b[i]).Append('\n');
                return sb.ToString();
            }
            var lcs = new int[n + 1, m + 1];
            for (var i = n - 1; i >= 0; i--)
                for (var j = m - 1; j >= 0; j--)
                    lcs[i, j] = a[start + i] == b[start + j] ? lcs[i + 1, j + 1] + 1 : global::System.Math.Max(lcs[i + 1, j], lcs[i, j + 1]);
            int x = 0, y = 0, shown = 0;
            while ((x < n || y < m) && shown < 200)
            {
                if (x < n && y < m && a[start + x] == b[start + y]) { sb.Append(""  "").Append(a[start + x]).Append('\n'); x++; y++; }
                else if (y < m && (x == n || lcs[x, y + 1] >= lcs[x + 1, y])) { sb.Append(""+ "").Append(b[start + y]).Append('\n'); y++; }
                else { sb.Append(""- "").Append(a[start + x]).Append('\n'); x++; }
                shown++;
            }
            if (endA < a.Length && shown < 200) sb.Append(""  "").Append(a[endA]).Append('\n');
            return sb.ToString();
        }

        private static string Resolve(string path, string callerFilePath)
        {
            if (global::System.IO.Path.IsPathRooted(path)) return path;
            var callerFolder = string.IsNullOrEmpty(callerFilePath) ? null : global::System.IO.Path.GetDirectoryName(callerFilePath);
            if (!string.IsNullOrEmpty(callerFolder) && global::System.IO.Directory.Exists(callerFolder))
                return global::System.IO.Path.GetFullPath(global::System.IO.Path.Combine(callerFolder, path));

            // Deterministic CI builds map source paths (for example to /_/...): look for the same folder above the test output.
            var baseFolder = global::System.AppDomain.CurrentDomain.BaseDirectory;
            if (!string.IsNullOrEmpty(callerFolder))
            {
                var parts = callerFolder!.Replace('\\', '/').Split(new[] { '/' }, global::System.StringSplitOptions.RemoveEmptyEntries);
                for (var skip = 0; skip < parts.Length; skip++)
                {
                    var tail = string.Join(global::System.IO.Path.DirectorySeparatorChar.ToString(), parts, skip, parts.Length - skip);
                    for (var folder = baseFolder; !string.IsNullOrEmpty(folder); folder = global::System.IO.Path.GetDirectoryName(folder))
                    {
                        var candidate = global::System.IO.Path.Combine(folder, tail);
                        if (global::System.IO.Directory.Exists(candidate)) return global::System.IO.Path.GetFullPath(global::System.IO.Path.Combine(candidate, path));
                    }
                }
            }
            return global::System.IO.Path.GetFullPath(global::System.IO.Path.Combine(baseFolder, path));
        }
";
    }
}
