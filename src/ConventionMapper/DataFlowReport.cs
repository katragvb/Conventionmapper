using System;
using System.Collections.Generic;
using System.Linq;
using System.Reflection;
using System.Text;
using ConventionMapper.Internal;

namespace ConventionMapper.Internal
{
    /// <summary>
    /// Builds a Markdown report of every map: where each destination member gets its value, and where members marked
    /// [Sensitive] can flow. Meant for code reviews and audits ("where does customer data go?").
    /// </summary>
    internal static class DataFlowReporter
    {
        public static string Build(IEnumerable<TypeMap> typeMaps)
        {
            var maps = typeMaps
                .OrderBy(m => Name(m.SourceType), StringComparer.Ordinal)
                .ThenBy(m => Name(m.DestinationType), StringComparer.Ordinal)
                .ToList();

            // sensitive member ("User.PasswordHash") -> destinations it is copied to
            var sensitive = new SortedDictionary<string, SortedSet<string>>(StringComparer.Ordinal);
            foreach (var map in maps)
                foreach (var member in PublicMembers(map.SourceType).Where(SensitiveGuard.IsSensitive))
                    Track(sensitive, member);

            var sections = new StringBuilder();
            var flowCount = 0;
            foreach (var map in maps)
            {
                sections.AppendLine();
                sections.Append("### `").Append(Name(map.SourceType)).Append("` → `").Append(Name(map.DestinationType)).AppendLine("`");
                sections.AppendLine();

                if (map.TypeConverter != null)
                {
                    sections.AppendLine("Converted as a whole by a type converter (`ConvertUsing`); individual members are not listed.");
                    continue;
                }

                sections.AppendLine("| Destination | Source | Notes |");
                sections.AppendLine("| --- | --- | --- |");

                if (map.ConstructorMap != null)
                {
                    foreach (var p in map.ConstructorMap.Parameters)
                    {
                        var destination = (p.Parameter.Name ?? "?") + " (constructor)";
                        var protectedDestination = SensitiveGuard.IsSensitive(p.Parameter);
                        flowCount++;
                        Row(sections, destination, protectedDestination, p.Source, map, sensitive, "constructor parameter");
                    }
                }

                foreach (var pm in map.PropertyMaps)
                {
                    var protectedDestination = SensitiveGuard.IsSensitive(pm.DestinationMember.Member);
                    if (pm.Ignored)
                    {
                        sections.Append("| ").Append(Cell(pm.DestinationName, protectedDestination)).AppendLine(" | — | ignored |");
                        continue;
                    }
                    if (pm.Source == null)
                    {
                        sections.Append("| ").Append(Cell(pm.DestinationName, protectedDestination)).AppendLine(" | — | not mapped |");
                        continue;
                    }
                    flowCount++;
                    Row(sections, pm.DestinationName, protectedDestination, pm.Source, map, sensitive, null);
                }

                foreach (var path in map.PathMaps)
                {
                    flowCount++;
                    var destination = string.Join(".", path.Path.Select(m => m.Name));
                    Row(sections, destination, SensitiveGuard.IsSensitive(path.Path[path.Path.Length - 1]), path.Source, map, sensitive, "ForPath");
                }
            }

            var sb = new StringBuilder();
            sb.AppendLine("# Data-flow report");
            sb.AppendLine();
            sb.AppendLine("Generated by ConventionMapper from the mapping configuration: where every destination member gets its value, and where members marked `[Sensitive]` can flow.");
            sb.AppendLine();
            sb.Append(maps.Count).Append(" map(s), ").Append(flowCount).AppendLine(" member flow(s).");
            sb.AppendLine();
            AppendSensitive(sb, sensitive);
            sb.AppendLine();
            sb.Append("## Maps");
            sb.AppendLine();
            sb.Append(sections);
            return sb.ToString();
        }

        internal static void AppendSensitive(StringBuilder sb, SortedDictionary<string, SortedSet<string>> sensitive)
        {
            sb.AppendLine("## Sensitive members");
            sb.AppendLine();
            if (sensitive.Count == 0)
            {
                sb.AppendLine("No mapped type has members marked `[Sensitive]`.");
                return;
            }
            sb.AppendLine("A sensitive member can only be copied into a destination member that is also `[Sensitive]`; any other copy fails the configuration.");
            sb.AppendLine();
            sb.AppendLine("| Member | Copied to |");
            sb.AppendLine("| --- | --- |");
            foreach (var pair in sensitive)
            {
                var targets = pair.Value.Count == 0 ? "not copied anywhere" : string.Join(", ", pair.Value.Select(t => "`" + t + "` (protected)"));
                sb.Append("| `").Append(pair.Key).Append("` | ").Append(targets).AppendLine(" |");
            }
        }

        private static void Row(StringBuilder sb, string destination, bool protectedDestination, ValueSource? source, TypeMap map,
            SortedDictionary<string, SortedSet<string>> sensitive, string? extraNote)
        {
            var notes = new List<string>();
            if (extraNote != null) notes.Add(extraNote);
            string description;
            if (source == null)
            {
                description = "—";
                notes.Add("default value");
            }
            else if (source is ChainSource chain)
            {
                description = "`" + string.Join(".", chain.Members.Select(m => m is MethodInfo ? m.Name + "()" : m.Name)) + "`";
                if (chain.Members.Length > 1) notes.Add("flattened");
                foreach (var member in chain.Members.Where(SensitiveGuard.IsSensitive))
                {
                    notes.Add("sensitive");
                    Track(sensitive, member).Add(Name(map.DestinationType) + "." + destination.Replace(" (constructor)", string.Empty));
                }
            }
            else
            {
                description = "`" + Escape(source.Describe()) + "`";
                notes.Add("computed");
            }

            sb.Append("| ").Append(Cell(destination, protectedDestination)).Append(" | ").Append(description).Append(" | ")
              .Append(string.Join(", ", notes)).AppendLine(" |");
        }

        private static string Cell(string destination, bool protectedDestination) =>
            protectedDestination ? destination + " (sensitive)" : destination;

        private static SortedSet<string> Track(SortedDictionary<string, SortedSet<string>> sensitive, MemberInfo member)
        {
            var key = Name(member.DeclaringType!) + "." + member.Name;
            if (!sensitive.TryGetValue(key, out var targets))
            {
                targets = new SortedSet<string>(StringComparer.Ordinal);
                sensitive[key] = targets;
            }
            return targets;
        }

        private static IEnumerable<MemberInfo> PublicMembers(Type type) =>
            type.GetProperties(BindingFlags.Instance | BindingFlags.Public).Cast<MemberInfo>()
                .Concat(type.GetFields(BindingFlags.Instance | BindingFlags.Public));

        private static string Escape(string text) => text.Replace("|", "\\|").Replace("`", "'").Replace("\r", " ").Replace("\n", " ");

        private static string Name(Type type) => ReflectionHelper.FriendlyName(type);
    }
}
