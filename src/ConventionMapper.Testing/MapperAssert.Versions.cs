using System;
using System.CodeDom.Compiler;
using System.Collections.Concurrent;
using System.Linq;
using System.Reflection;

namespace ConventionMapper.Testing
{
    public static partial class MapperAssert
    {
        private const string GeneratorTool = "ConventionMapper.SourceGenerator";
        private static readonly ConcurrentDictionary<Type, string?> GeneratorVersions = new ConcurrentDictionary<Type, string?>();

        /// <summary>
        /// The checks read what the generator emits (WriteSets, Lineage, GeneratedCode); another major or minor version of
        /// the generator can emit it differently, which shows up as confusing failures. Fails with both versions instead.
        /// Mappers without a [GeneratedCode] stamp are not checked.
        /// </summary>
        private static void CheckGeneratorVersion(Type mapperType)
        {
            var generator = GeneratorVersions.GetOrAdd(mapperType, ReadGeneratorVersion);
            var testing = OwnVersion();
            if (generator == null || testing == null || MajorMinor(generator) == MajorMinor(testing)) return;
            throw new MapperAssertException(
                "'" + mapperType.FullName + "' was generated by " + GeneratorTool + " " + generator + ", but this is ConventionMapper.Testing " +
                testing + ". Reference the same major and minor version of both packages.");
        }

        private static string? ReadGeneratorVersion(Type mapperType) =>
            mapperType.GetMethods(BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.Static | BindingFlags.DeclaredOnly)
                .Select(m => m.GetCustomAttribute<GeneratedCodeAttribute>())
                .FirstOrDefault(a => a != null && a.Tool == GeneratorTool)?.Version;

        private static string? OwnVersion()
        {
            var version = typeof(MapperAssert).Assembly.GetCustomAttribute<AssemblyInformationalVersionAttribute>()?.InformationalVersion;
            if (version == null) return null;
            var plus = version.IndexOf('+');
            return plus >= 0 ? version.Substring(0, plus) : version;
        }

        /// <summary>"1.9.1-preview.2" -> "1.9".</summary>
        private static string MajorMinor(string version)
        {
            var parts = version.Split('-')[0].Split('.');
            return parts.Length >= 2 ? parts[0] + "." + parts[1] : parts[0];
        }
    }
}
